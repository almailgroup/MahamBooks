/**
 * Where a custom word is kept in `company.labels`: Arabic words under
 * "ar.<key>", the other languages (English in practice) under the plain key,
 * so a bilingual document can override both halves.
 */
export function overrideKey(language: LabelLanguage, key: LabelKey): string {
  return language === 'ar' ? `ar.${key}` : key;
}

/** The printed words of one language, with the company's custom words applied. */
export function getLabels(
  language: DocumentLanguage = 'en',
  overrides: Record<string, string> = {},
): Labels {
  const lang: LabelLanguage = language === 'ar-en' ? 'ar' : language;
  const base = translations[lang] ?? en;
  const result = { ...base };
  for (const key of LABEL_KEYS) {
    const custom = overrides[overrideKey(lang, key)];
    if (typeof custom === 'string' && custom.trim() !== '') result[key] = custom.trim();
  }
  return result;
}

/** Built-in words, without custom overrides (placeholders in the settings). */
export function defaultLabels(language: LabelLanguage): Labels {
  return { ...(translations[language] ?? en) };
}

/**
 * The words of a document: the main language, plus English for bilingual
 * (`ar-en`) documents, printed next to or under the Arabic.
 */
export function documentLabels(
  language: DocumentLanguage,
  overrides: Record<string, string> = {},
): { primary: Labels; secondary: Labels | null } {
  if (language === 'ar-en') {
    return { primary: getLabels('ar', overrides), secondary: getLabels('en', overrides) };
  }
  return { primary: getLabels(language, overrides), secondary: null };
}
