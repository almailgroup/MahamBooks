/** Languages with their own set of printed words (bilingual documents combine two). */
export type LabelLanguage = Exclude<DocumentLanguage, 'ar-en'>;

/** Arabic documents (and the Arabic half of bilingual ones) are laid out right to left. */
export function isRtlLanguage(language: DocumentLanguage | null | undefined): boolean {
  return language === 'ar' || language === 'ar-en';
}

